package com.marketplace.enums;

/**
 * Where a promotional banner should be rendered on the storefront.
 *   HOME     - top hero banner carousel on the homepage (default, existing behaviour).
 *   CATEGORY - banner shown under the category section (below the category
 *              pills, above the product grid) on the homepage.
 */
public enum BannerPlacement {
    HOME,
    CATEGORY
}